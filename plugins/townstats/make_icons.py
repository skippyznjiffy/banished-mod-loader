"""Writes icons.h: the Lucide icons Town Stats uses, cut out of third_party/lucide/lucide.ttf
and embedded as bytes, with a UTF-8 string per icon. Needs fonttools (pip install fonttools).
Run it again after changing ICONS."""
import io
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ICONS = [
    "users", "user", "graduation-cap", "baby", "heart-pulse", "smile", "book-open", "shirt",
    "layout-dashboard", "wheat", "package", "chart-line", "chart-spline", "x", "trending-up",
    "trending-down", "hourglass", "utensils", "sprout", "scale", "warehouse",
]

here = Path(__file__).resolve().parent
lucide = here.parent.parent / "third_party" / "lucide"
codepoints = json.loads((lucide / "codepoints.json").read_text(encoding="utf-8"))

font = TTFont(lucide / "lucide.ttf")
options = subset.Options()
options.notdef_outline = True
subsetter = subset.Subsetter(options)
subsetter.populate(unicodes=[codepoints[name] for name in ICONS])
subsetter.subset(font)
data = io.BytesIO()
font.save(data)
raw = data.getvalue()

lines = [
    "// generated by make_icons.py from Lucide (ISC license, third_party/lucide/LICENSE)",
    "#pragma once",
    "",
]
for name in ICONS:
    utf8 = chr(codepoints[name]).encode("utf-8")
    lines.append(f'#define ICON_{name.upper().replace("-", "_")} "{"".join(f"\\x{b:02x}" for b in utf8)}"')
first, last = min(codepoints[n] for n in ICONS), max(codepoints[n] for n in ICONS)
lines += ["", f"constexpr unsigned short kIconFirst = 0x{first:x};", f"constexpr unsigned short kIconLast = 0x{last:x};", ""]
lines.append(f"alignas(4) const unsigned char kIconFont[{len(raw)}] = {{")
for i in range(0, len(raw), 20):
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in raw[i:i + 20]) + ",")
lines.append("};")
(here / "icons.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"icons.h: {len(ICONS)} icons, {len(raw)} bytes")
